export const KRW_PER_USD = 1350;

export function formatCurrency(usdAmount: number, lang: Language): string {
  if (lang === 'ko') {
    const krw = Math.round(usdAmount * KRW_PER_USD);
    if (krw >= 100_000_000) {
      const eok = (krw / 100_000_000).toFixed(2).replace(/\.00$/, '');
      return `${eok}억 원`;
    }
    const man = Math.round(krw / 10_000);
    return `${man.toLocaleString()}만 원`;
  }
  return `$${Math.round(usdAmount).toLocaleString()}`;
}

export function getFacilityDisplayName(facility: Facility, lang: Language): string {
  if (lang === 'ko' && facility.nameKo) {
    return facility.nameKo;
  }
  return facility.name;
}

